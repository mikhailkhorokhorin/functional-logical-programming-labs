failing_mark(Mark) :-
    Mark =< 2.

students(Students) :-
    findall(Student, grade(_, Student, _, _), All),
    sort(All, Students).

student_all_exams_passed(Student) :-
    findall(Mark, grade(_, Student, _, Mark), Marks),
    Marks \= [],
    \+ (member(Mark, Marks), failing_mark(Mark)).

student_average_grade(Student, Avg) :-
    findall(Mark, grade(_, Student, _, Mark), Marks),
    Marks \= [],
    sum_list(Marks, Sum),
    length(Marks, Count),
    Avg is Sum / Count.

print_students_summary :-
    students(Students),
    forall(member(Student, Students),
        (   student_average_grade(Student, Avg),
            (   student_all_exams_passed(Student)
            ->  Status = 'all exams passed'
            ;   Status = 'failed at least one exam'
            ),
            format('~w: average ~2f, ~w~n', [Student, Avg, Status])
        )).

subject_failed_count(Subject, Count) :-
    findall(Student, (grade(_, Student, Subject, Mark), failing_mark(Mark)), Failed),
    sort(Failed, UniqueFailed),
    length(UniqueFailed, Count).

print_subject_fail_summary :-
    findall(Subject, grade(_, _, Subject, _), Subjects),
    sort(Subjects, UniqueSubjects),
    forall(member(Subject, UniqueSubjects),
        (   subject_failed_count(Subject, Count),
            format('~w: ~d failed~n', [Subject, Count])
        )).

group_top_students(Group, MaxAvg, TopStudents) :-
    findall(Student, grade(Group, Student, _, _), StudentsDup),
    sort(StudentsDup, Students),
    findall(Avg-Student,
        (   member(Student, Students),
            student_average_grade(Student, Avg)
        ), AvgPairs),
    max_member(MaxAvg-_, AvgPairs),
    findall(Student, member(MaxAvg-Student, AvgPairs), TopStudents).

print_group_max_average :-
    findall(Group, grade(Group, _, _, _), Groups),
    sort(Groups, UniqueGroups),
    forall(member(Group, UniqueGroups),
        (   group_top_students(Group, MaxAvg, TopStudents),
            format('Group ~w: highest average ~2f, students ~w~n', [Group, MaxAvg, TopStudents])
        )).

main :-
    writeln('Average grade and exam status per student:'),
    print_students_summary,
    nl,
    writeln('Failed students per subject:'),
    print_subject_fail_summary,
    nl,
    writeln('Best students per group:'),
    print_group_max_average.

:- initialization(main, main).
